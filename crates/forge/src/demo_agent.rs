//! Deterministic controlled process used to exercise the infrastructure of
//! Forge (scheduler, worktrees, supervision, cancellation, recovery) without
//! depending on real model execution.
//!
//! This is deliberately NOT presented as an AI agent: it is a test driver
//! that behaves like a coding agent (writes files in its worktree, prints
//! progress lines, can fail or hang on request).

use std::io::Write;
use std::path::Path;

use crate::cli::DemoAgentArgs;

pub fn run(args: &DemoAgentArgs) -> std::process::ExitCode {
    if args.version {
        println!("demo-agent 0.1.0 (forge controlled process)");
        return std::process::ExitCode::SUCCESS;
    }

    let name = &args.name;
    if args.auth_fail {
        println!("[{name}] starting");
        eprintln!("Error: not logged in. Please run `{name} login` to authenticate.");
        return std::process::ExitCode::from(1);
    }
    if let Some(prompt) = &args.prompt {
        let first_line = prompt.lines().next().unwrap_or_default();
        println!("[{name}] prompt received: {first_line}");
    }

    println!(
        "[{name}] starting; workdir={}",
        std::env::current_dir().unwrap_or_default().display()
    );
    let mut json_out = std::io::stdout();
    let _ = writeln!(
        json_out,
        r#"{{"type":"session.started","message":"controlled process {name} online"}}"#
    );
    let _ = json_out.flush();

    for step in 1..=args.steps.max(1) {
        println!("[{name}] step {step}/{}", args.steps.max(1));
        std::thread::sleep(std::time::Duration::from_millis(args.sleep_ms));
    }

    let cwd = std::env::current_dir().unwrap_or_default();
    let mut written = vec![];
    for file in &args.files {
        let path = cwd.join(file);
        if let Some(parent) = path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        let content = format!("generated by {name}\nfile: {file}\n");
        match std::fs::write(&path, content) {
            Ok(()) => {
                println!("[{name}] wrote {file}");
                written.push(file.clone());
                let _ = writeln!(
                    json_out,
                    r#"{{"type":"file.written","message":"wrote {file}"}}"#
                );
            }
            Err(e) => {
                eprintln!("[{name}] error: cannot write {file}: {e}");
                return std::process::ExitCode::from(3);
            }
        }
    }
    for file in &args.edits {
        let path = cwd.join(file);
        match append_line(&path, &format!("edited by {name}\n")) {
            Ok(()) => println!("[{name}] edited {file}"),
            Err(e) => {
                eprintln!("[{name}] error: cannot edit {file}: {e}");
                return std::process::ExitCode::from(3);
            }
        }
    }
    let _ = json_out.flush();

    if args.fail {
        eprintln!(
            "[{name}] error: simulated failure after writing {} files",
            written.len()
        );
        println!("[{name}] done with failure");
        return std::process::ExitCode::from(2);
    }

    if args.hang_ms > 0 {
        println!("[{name}] hanging for {} ms", args.hang_ms);
        let deadline = std::time::Instant::now() + std::time::Duration::from_millis(args.hang_ms);
        while std::time::Instant::now() < deadline {
            std::thread::sleep(std::time::Duration::from_millis(100));
        }
    }

    println!("[{name}] done");
    std::process::ExitCode::SUCCESS
}

fn append_line(path: &Path, line: &str) -> std::io::Result<()> {
    use std::fs::OpenOptions;
    let mut file = OpenOptions::new().create(true).append(true).open(path)?;
    file.write_all(line.as_bytes())
}
